"""Generate sunshine-pc/files.cmake from sms/configure.py.

Every Object(...) with a source file is listed, minus the units in excluded-units.txt (not built by the port) and
blocked-units.txt (cannot build yet, with the reason). Nothing is listed by hand. Re-run after configure.py changes:
    python tools/gen-files.py
"""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
pc = os.path.abspath(os.path.join(here, ".."))
sms = os.path.abspath(os.path.join(pc, "..", "sms"))


def rules(name):
    path = os.path.join(pc, name)
    out = []
    for ln in open(path, encoding="utf8"):
        if ln.strip() and not ln.startswith("#"):
            out.append(ln.split("|", 1)[0].strip())
    return out


excluded = rules("excluded-units.txt")
blocked = rules("blocked-units.txt")

cfg = open(os.path.join(sms, "configure.py"), encoding="utf8").read()
units = [p for _, p in re.findall(r'Object\((\w+),\s*"([^"]+)"', cfg)]
units = [u for u in units if u.endswith((".cpp", ".c")) and os.path.exists(os.path.join(sms, "src", u))]

keep = [u for u in units if not any(u.startswith(r) for r in excluded + blocked)]
cxx_c = [u for u in keep if u.endswith(".c") and u.startswith("THPPlayer/")]  # built -lang=c++ by the decomp

lines = [
    "# Generated by tools/gen-files.py from sms/configure.py. Do not edit.",
    f"# {len(units)} units, {len([u for u in units if any(u.startswith(r) for r in excluded)])} excluded, "
    f"{len([u for u in units if any(u.startswith(r) for r in blocked)])} blocked, {len(keep)} built.",
    "set(SMS_GAME_SOURCES",
]
lines += [f"    ${{SMS_SRC_DIR}}/{u}" for u in keep]
lines += [")", "", "set(SMS_CXX_C_SOURCES"]
lines += [f"    ${{SMS_SRC_DIR}}/{u}" for u in cxx_c]
lines += [")", ""]
open(os.path.join(pc, "files.cmake"), "w", encoding="utf8", newline="\n").write("\n".join(lines))
print(f"{len(keep)} built, {len(units) - len(keep)} not built")
