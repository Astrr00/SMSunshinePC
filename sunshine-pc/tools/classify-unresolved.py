"""Sort the linker's unresolved symbols by cause and write docs/unresolved.md.

Usage: python tools/classify-unresolved.py [link log, default tools/_link.log]
Cause rules (first match wins) are plain prefix tests, so the table is reproducible from the log alone.
"""
import collections
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
log = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "_link.log")
syms = sorted({m.group(1).strip() for m in re.finditer(r"undefined symbol: (.+)", open(log, encoding="utf8", errors="replace").read())})

RULES = [
    ("OS layer (threads, mutex, cond, message queue, stopwatch, interrupts, font, reset, PPC intrinsics)",
     r"^(OS|PPC|__OS)"),
    ("AI / ARAM / DSP hardware (JAudio output path)", r"^(AI|AR|DSP)"),
    ("VI (video interface, retrace and framebuffer hooks)", r"^VI"),
    ("GX/GD leftovers (debug, perf, peek/poke and sync APIs Aurora does not provide)", r"^(GX|GD)"),
    ("__fres (needs a bit-exact reciprocal estimate, see platform-notes.md)", r"^__fres$"),
    ("Hx_ wiper library (called from GC2D/ScrnFader.cpp, not part of the decomp sources)", r"^Hx_"),
]


def cause(s):
    for name, rx in RULES:
        if re.search(rx, s):
            return name
    if "::" in s or re.match(r"^(class|struct) ", s):
        return "Game/JSystem method or static with no definition (empty or unfinished decomp source)"
    return "Game global with no definition (empty or unfinished decomp source)"


groups = collections.OrderedDict()
for s in syms:
    groups.setdefault(cause(s), []).append(s)

out = ["# Unresolved symbols at link time", "",
       f"Generated by `tools/classify-unresolved.py` from `{os.path.basename(log)}`. {len(syms)} distinct symbols.", "",
       "| Cause | Symbols |", "| --- | ---: |"]
for k, v in sorted(groups.items(), key=lambda kv: -len(kv[1])):
    out.append(f"| {k} | {len(v)} |")
out.append("")
for k, v in sorted(groups.items(), key=lambda kv: -len(kv[1])):
    out += [f"## {k} ({len(v)})", ""] + [f"- `{s}`" for s in v] + [""]
dst = os.path.join(here, "..", "docs", "unresolved.md")
open(dst, "w", encoding="utf8", newline="\n").write("\n".join(out))
for k, v in sorted(groups.items(), key=lambda kv: -len(kv[1])):
    print(f"{len(v):4}  {k}")
